func (e *executiions) addExecutionIfNeeded(a exinfra.EventAttrib) error {
	for _, v := range a.DepsTuples {
		d = v.Brick.Dependencies[v.Name]
		d.Value = a.Value
		switch  d.TriggerType {
		case "weak":
			continue
		case "classic":
			// add execution
		case "is_true()", "is_true":
			if testEq([]byte("true"), a.Value) {
				// add execution
			} 
		case "is_false()", "is_false":
			if testEq([]byte("false"), a.Value) {
				// add execution
			}
		case "is_null()", "is_null":
			if testEq([]byte("null"), a.Value) ||
				testEq([]byte{}, a.Value) {
				// add execution
			}
		case "is_not_null()", "is_not_null":
			if ! testEq([]byte("null"), a.Value) &&
				! testEq([]byte{}, a.Value) {
				// add execution
			}
		case "is_empty()", "is_empty":
			if testEq([]byte("[]"), a.Value) ||
				testEq([]byte("{}"), a.Value) ||
				testEq([]byte("\"\""), a.Value) ||
				testEq([]byte{}, a.Value) {
				// add execution
			}
		case "is_not_empty()", "is_not_empty":
			if ! testEq([]byte("[]"), a.Value) &&
				! testEq([]byte("{}"), a.Value) &&
				! testEq([]byte("\"\""), a.Value) &&
				! testEq([]byte{}, a.Value) {
				// add execution
			}
		case "is_nothing()", "is_nothing":
			if testEq([]byte("null"), a.Value) || 
				testEq([]byte("[]"), a.Value) || 
				testEq([]byte("{}"), a.Value) ||
				testEq([]byte("\"\""), a.Value) ||
				testEq([]byte{}, a.Value) {
				// add execution
			}
		case "is_not_nothing()", "is_not_nothing":
			if ! testEq([]byte("null"), a.Value) && 
				! testEq([]byte("[]"), a.Value) &&
				! testEq([]byte("{}"), a.Value) &&
				! testEq([]byte("\"\""), a.Value) &&
				! testEq([]byte{}, a.Value) {
				// add execution
			}
		default:
			specialTriggerTypeTest()
		}

		if d.TriggerType == "weak" {
			continue
		}
	}
}

func (r *Run) addExecutions(
	i int, 
	actionEvents []byte, // actionEvents is not an []byte but a map[string]interface{} but maybe it is : module line 219 : events[eventName], err = os.ReadFile(path) 
	preOutput []byte, 
	postOutput []byte, 
) (
	err error
) {
	brickName := r.list[i].Brick.Name
	src := exinfra.OUTPUT_SOURCE
	//map[brickName][src][jsonPath][]EventAttrib 
	for jsonPath, event := range r.infra.Events[brickName][src] {
		initialValue = getJsonPathValue(preOutput, jsonPath)
		endValue = getJsonPathValue(postOutput, jsonPath)
		if !testEq(initialValue, endValue) {
			r.infra.Events[brickName][src][jsonPath].HasOccured = true
			
			// ADD EXECUTION
			r.AddExecution()
		}
		r.infra.Events[brickName][src][jsonPath].Value = endValue
	}

	src = exinfra.EVENT_SOURCE
	jsonNull = []byte("null")
	for jsonPath, event := range r.infra.Events[brickName][src] {
		value = getJsonPathValue(actionEvents, jsonPath)
		if !testEq(value, jsonNull) {
			r.infra.Events[brickName][src][jsonPath].HasOccured = true
			r.infra.Events[brickName][src][jsonPath].Value = value
		}
	}

}

func (r *Run) skipFollowing(index int) {
	for i=(index+1) ; i<len(r.list) ; i++ {
		r.list[i].Skipped = true
		r.list[i].Triggered
	}
}


