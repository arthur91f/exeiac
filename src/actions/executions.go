func init() {
	specialTriggersStr := []string{
		`equal`,
		`contains`,
		`match`,
	}
	var r *regexp.Regexp
	for _, s := range specialTriggersStr {
		r = regexp.MustCompile(`^ *` + s + `(`)
		specialTriggers[s] = r
		r = regexp.MustCompile(`^ *not_` + s + `(`)
		specialTriggers[`not_` + s] = r
	}
}

